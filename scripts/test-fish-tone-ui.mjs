// Exercise the real console against an isolated bridge, with no QQ/DSH peers.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { bridgeHarness } from './audit-bridge-harness.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const html = await fs.readFile(new URL('../public/console.html', import.meta.url), 'utf8');
const h = await bridgeHarness({ files: { 'public/console.html': html }, config: { dualMode: { enabled: true, ownerPreset: 'standard' } } });
const server = h.startConsoleServer(); if (!server.listening) await new Promise(r => server.once('listening', r));
const baseUrl = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  const candidate = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
  browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { executablePath: candidate } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === baseUrl ? route.continue() : route.abort());
  await page.goto(baseUrl + '/?token=fixture-console-token');
  await page.locator('[data-view="persona"]').click();
  await page.locator('#fishTonePanel > summary').click();
  await page.locator('#fishToneMessage').filter({ hasText: '表达设置已读取' }).waitFor();
  assert.equal(await page.locator('#fishToneRewrite').isChecked(), false);
  await page.locator('#fishToneScope').selectOption('conversations');
  await page.locator('#fishToneTarget').fill('group:456');
  await page.locator('#fishToneStyle').selectOption('cute');
  await page.locator('#fishToneSave').click();
  await page.locator('#fishToneMessage').filter({ hasText: '表达设置已保存' }).waitFor();
  const settings = JSON.parse(await fs.readFile(path.join(h.temp, 'state/fish-tone.json'), 'utf8'));
  assert.equal(settings.conversations['group:456'].style, 'cute'); assert.equal(settings.defaults.rewriteEnabled, false);
  await page.locator('#fishTonePreviewText').fill('不是速度慢，而是代码有问题。最重要的是先分析再处理。');
  await page.locator('#fishTonePreview').click();
  await page.locator('#fishToneResult').filter({ hasText: 'hitCount' }).waitFor();
  await page.locator('#fishToneOperation').selectOption('meme');
  await page.locator('#fishTonePreviewText').fill('破防');
  await page.locator('#fishTonePreview').click();
  await page.locator('#fishToneResult').filter({ hasText: 'memes' }).waitFor();
  assert.match(await page.locator('#fishToneResult').textContent(), /破防/);
  await page.locator('#fishToneOperation').selectOption('tone');
  await page.locator('#fishTonePreviewText').fill('这个功能挺有趣。');
  await page.locator('#fishTonePreview').click();
  await page.locator('#fishToneMessage').filter({ hasText: '未启用' }).waitFor();
  await page.locator('#fishToneReset').click();
  await page.locator('#fishToneMessage').filter({ hasText: '表达设置已保存' }).waitFor();
  assert.equal(JSON.parse(await fs.readFile(path.join(h.temp, 'state/fish-tone.json'), 'utf8')).conversations['group:456'], undefined);
  const output = process.argv.find(v => v.startsWith('--screenshot='))?.slice(13);
  if (output) await page.locator('#fishTonePanel').screenshot({ path: output });
  assert.deepEqual(errors, []); assert.equal(h.calls.sent.length, 0);
  console.log('PASS real console: load, per-conversation save, judge, meme, disabled rewrite, restore inheritance; no QQ sends');
} finally { await browser?.close(); server.closeAllConnections(); await new Promise(r => server.close(r)); await h.close(); }
